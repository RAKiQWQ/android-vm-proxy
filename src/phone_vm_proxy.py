#!/usr/bin/env python3
"""Forward an Android phone's HTTP proxy into its Linux VM using paired ADB."""
from __future__ import annotations

import argparse
from dataclasses import asdict, dataclass
import ipaddress
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import time

UNIT = "android-vm-proxy.service"


@dataclass(frozen=True)
class Config:
    adb_host: str = "auto"
    adb_port: int | None = None
    phone_port: int = 10808
    vm_port: int = 18080

    @classmethod
    def parse(cls, data: dict) -> Config:
        if not isinstance(data, dict) or set(data) - set(cls.__dataclass_fields__):
            raise ValueError("Config accepts only adb_host, adb_port, phone_port and vm_port")
        config = cls(**data)
        host = config.adb_host
        if not isinstance(host, str):
            raise ValueError("adb_host must be auto, an IP address or a hostname")
        try:
            ipaddress.ip_address(host)
        except ValueError:
            if not re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9_.-]*[A-Za-z0-9])?", host):
                raise ValueError("Invalid adb_host") from None
        for name in ("adb_port", "phone_port", "vm_port"):
            value = getattr(config, name)
            if name == "adb_port" and value is None:
                continue
            if type(value) is not int or not 1 <= value <= 65535:
                raise ValueError(name + " must be in 1..65535")
        if config.vm_port in (5037, 3773, 1455):
            raise ValueError("vm_port conflicts with ADB, T3 or the login callback")
        if config.adb_port == config.phone_port:
            raise ValueError("The phone proxy and wireless debugging ports must differ")
        return config


def run(*command: str) -> tuple[int, str]:
    result = subprocess.run(command, capture_output=True, text=True, timeout=10)
    return result.returncode, (result.stdout + result.stderr).strip()


def endpoint(config: Config, port: int | None = None) -> str:
    selected = config.adb_port if port is None else port
    if selected is None:
        raise RuntimeError("Run phone-vm-proxy configure CONNECTION_PORT first")
    host = config.adb_host
    if host == "auto":
        code, output = run("ip", "-4", "route", "show", "default")
        match = re.search(r"\bvia\s+([0-9.]+)", output)
        if code or not match:
            raise RuntimeError("No IPv4 default gateway; configure with --host PHONE_ADDRESS")
        host = match.group(1)
    return (f"[{host}]" if ":" in host else host) + f":{selected}"


def adb(*arguments: str, device: str | None = None) -> tuple[int, str]:
    command = ["adb", "-H", "127.0.0.1", "-P", "5037"]
    if device:
        command += ["-s", device]
    return run(*command, *arguments)


def environment(config: Config) -> dict[str, str]:
    proxy = f"http://127.0.0.1:{config.vm_port}"
    return {
        "HTTP_PROXY": proxy, "HTTPS_PROXY": proxy, "ALL_PROXY": proxy,
        "http_proxy": proxy, "https_proxy": proxy, "all_proxy": proxy,
        "NO_PROXY": "localhost,127.0.0.1,::1", "no_proxy": "localhost,127.0.0.1,::1",
    }


def private_write(path: Path, text: str) -> None:
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        os.chmod(temporary, 0o600)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def read_config(directory: Path) -> Config:
    return Config.parse(json.loads((directory / "config.json").read_text(encoding="utf-8")))


def save_config(directory: Path, config: Config) -> None:
    values = environment(config)
    private_write(directory / "env.sh", "# Generated by Android VM Proxy\n" +
                  "".join(f"export {key}='{value}'\n" for key, value in values.items()))
    private_write(directory / "config.json", json.dumps(asdict(config), indent=2) + "\n")


def require_stopped() -> None:
    code, state = run("systemctl", "--user", "is-active", UNIT)
    if code not in (3, 4) or state not in {"inactive", "failed", "unknown"}:
        raise RuntimeError("Stop android-vm-proxy.service before configure, once or cleanup")


def forward_rows() -> list[list[str]]:
    code, output = adb("forward", "--list")
    if code:
        raise RuntimeError("Cannot list ADB forward mappings")
    return [line.split() for line in output.splitlines() if line.strip()]


def mapping(config: Config) -> list[str]:
    return [endpoint(config), f"tcp:{config.vm_port}", f"tcp:{config.phone_port}"]


def verify_loopback(port: int) -> None:
    code, output = run("ss", "-H", "-ltn")
    if code:
        raise RuntimeError("Cannot inspect the VM listener with ss")
    hosts = []
    for line in output.splitlines():
        fields = line.split()
        if len(fields) >= 4:
            host, _, selected = fields[3].rpartition(":")
            if selected == str(port):
                hosts.append(host.strip("[]"))
    if not hosts or any(host not in {"127.0.0.1", "::1"} for host in hosts):
        raise RuntimeError("VM proxy must listen only on loopback; check ADB was not started with -a")


def cleanup(config: Config) -> None:
    if config.adb_port is None:
        return
    expected = mapping(config)
    if expected in forward_rows():
        code, _ = adb("forward", "--remove", expected[1], device=expected[0])
        if code:
            raise RuntimeError("Cannot remove the matching proxy forward")


def cycle(config: Config) -> str:
    expected = mapping(config)
    device, local, remote = expected
    code, state = adb("get-state", device=device)
    if code or state != "device":
        adb("connect", device)
        code, state = adb("get-state", device=device)
    if code or state != "device":
        raise RuntimeError("Wireless ADB unavailable; check pairing and the connection port")
    rows = forward_rows()
    if any(len(row) == 3 and row[1] == local and row != expected for row in rows):
        raise RuntimeError("VM port belongs to another ADB forward; choose another --vm-port")
    created = expected not in rows
    if created:
        code, _ = adb("forward", "--no-rebind", local, remote, device=device)
        if code:
            raise RuntimeError("Cannot bind the VM proxy port; check for another listener")
    try:
        verify_loopback(config.vm_port)
    except (OSError, RuntimeError, subprocess.SubprocessError):
        if created:
            cleanup(config)
        raise
    return f"Forward configured: http://127.0.0.1:{config.vm_port}; verify upstream access with curl"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    pair = commands.add_parser("pair", help="Pair with wireless debugging; enter the code in adb's prompt")
    pair.add_argument("port", type=int)
    pair.add_argument("--host")
    configure = commands.add_parser("configure", help="Save ports and generate the shell environment")
    configure.add_argument("port", type=int, help="Wireless debugging connection port")
    configure.add_argument("--host")
    configure.add_argument("--phone-port", type=int)
    configure.add_argument("--vm-port", type=int)
    for name in ("run", "once", "cleanup", "env"):
        commands.add_parser(name)
    args = parser.parse_args(argv)
    directory = Path.home() / ".config/android-vm-proxy"
    config = read_config(directory)
    if args.command == "pair":
        selected = Config.parse({**asdict(config), "adb_host": args.host or config.adb_host, "adb_port": args.port})
        return subprocess.call(["adb", "-H", "127.0.0.1", "-P", "5037", "pair", endpoint(selected)])
    if args.command == "env":
        print("".join(f"{key}={value}\n" for key, value in environment(config).items()), end="")
        return 0
    if args.command in {"configure", "once", "cleanup"}:
        require_stopped()
        if args.command == "configure":
            values = {**asdict(config), "adb_port": args.port}
            for option, field in ((args.host, "adb_host"), (args.phone_port, "phone_port"), (args.vm_port, "vm_port")):
                if option is not None:
                    values[field] = option
            replacement = Config.parse(values)
            cleanup(config)
            save_config(directory, replacement)
            print("Saved. Start the service, then source ~/.config/android-vm-proxy/env.sh")
        elif args.command == "cleanup":
            cleanup(config)
        else:
            print(cycle(config))
        return 0
    previous = None
    while True:
        try:
            message = cycle(read_config(directory))
        except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
            message = "Proxy link error: " + str(error)
        if message != previous:
            print(message, flush=True)
            previous = message
        time.sleep(12)


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print("phone-vm-proxy:", str(error), file=sys.stderr)
        raise SystemExit(1)
